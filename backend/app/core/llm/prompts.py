MAP_SYSTEM = """\
Ты — системный аналитик. Тебе дана расшифровка встречи заказчика
и технического специалиста. Составь карту разговора: она нужна, чтобы затем
корректно извлечь требования.

Отвечай ТОЛЬКО валидным JSON по схеме:
{
  "summary": "3-5 предложений: о каком продукте шла речь и зачем он нужен",
  "topics": [
    {"title": "краткое название темы",
     "summary": "1-2 предложения",
     "segment_ids": [номера сегментов [#N], где обсуждалась тема]}
  ],
  "roles_mentioned": ["роли пользователей, упомянутые в разговоре"],
  "glossary": {"термин": "что он значит в контексте этого проекта"}
}

Требования к содержанию:
  * topics — 3-10 тем в порядке обсуждения;
  * roles_mentioned — только реально названные роли, без выдуманных;
  * glossary — доменные термины и аббревиатуры заказчика, которые
    непонятны без контекста. Пустой объект, если таких нет.
"""


def build_map_user(full_text: str, meta: TranscriptMeta, limit: int = 24000) -> str:
    """
    Один дешёвый вызов на весь транскрипт. Если разговор длинный — берём
    начало и конец: там обычно постановка задачи и итоговые договорённости.
    """
    if len(full_text) > limit:
        head = full_text[: int(limit * 0.6)]
        tail = full_text[-int(limit * 0.4) :]
        body = f"{head}\n\n[…середина расшифровки опущена…]\n\n{tail}"
    else:
        body = full_text

    header = []
    if meta.title:
        header.append(f"Встреча: {meta.title}")
    if meta.project:
        header.append(f"Проект: {meta.project}")
    if meta.participants:
        header.append(f"Участники: {', '.join(meta.participants)}")
    prefix = "\n".join(header)
    if prefix:
        prefix += "\n\n"

    return f"{prefix}РАСШИФРОВКА РАЗГОВОРА:\n{body}"


