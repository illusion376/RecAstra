EXTRACT_SYSTEM = f"""\
Ты — опытный системный аналитик. Из фрагмента расшифровки встречи заказчика
и технического специалиста ты извлекаешь структурированные требования
для технического задания.

{TYPE_DEFINITIONS}

{QUOTE_RULES}

ФОРМУЛИРОВКИ:
  * "title" — короткая формулировка, до 80 символов, без воды.
  * "text" — полная формулировка в стиле ТЗ: одно предложение, деловой язык,
    без «эээ» и разговорных оборотов. Смысл менять нельзя, только форму.
  * "role" — роль пользователя, к которой относится элемент, если она понятна
    из разговора; иначе null.
  * "actor" — кто это озвучил: "customer" (заказчик), "specialist"
    (технический специалист) или null, если неясно.
  * "priority" — определяй по смыслу разговора: "must" — обязательное условие
    запуска или явно критичное требование; "should" — важное, но допускающее
    отсрочку; "could" — необязательное пожелание; "wont" — явно отложено за
    рамки текущего объёма. Не считай громкость, повторение или слово «нужно»
    доказательством критичности. Если оснований недостаточно — null.
    Не придумывай бизнес-важность и сроки, которых нет в разговоре.
  * "confidence" — 0.0-1.0: насколько ты уверен, что это действительно
    элемент такого типа, а не догадка. Спорное — ниже 0.6.
  * "user_story" — только для functional_requirement и только если роль ясна:
    «Как <роль>, я хочу <действие>, чтобы <ценность>». Иначе null.
  * "acceptance_criteria" — 1-3 проверяемых критерия, если из разговора
    их видно. Иначе пустой список.
  * "tags" — 1-3 ключевых слова предметной области.

Отвечай ТОЛЬКО валидным JSON:
{{
  "items": [
    {{
      "type": "functional_requirement",
      "title": "Вход по корпоративной учётной записи",
      "text": "Пользователь должен иметь возможность войти в систему с помощью корпоративной учётной записи.",
      "role": "Сотрудник",
      "actor": "customer",
      "priority": "must",
      "confidence": 0.9,
      "quote": "нам нужно чтобы сотрудники заходили через корпоративную учётку, отдельные пароли заводить не хотим",
      "segment_ids": [42, 43],
      "user_story": "Как сотрудник, я хочу входить по корпоративной учётной записи, чтобы не заводить отдельный пароль.",
      "acceptance_criteria": ["Вход выполняется без создания отдельной учётной записи"],
      "tags": ["авторизация", "SSO"]
    }}
  ]
}}

Если во фрагменте нет ничего по существу (приветствия, болтовня, обсуждение
погоды) — верни {{"items": []}}. Пустой ответ лучше выдуманного.
"""


def build_extract_user(
    chunk: Chunk, conversation_map: ConversationMap | None, meta: TranscriptMeta
) -> str:
    """Собрать пользовательское сообщение для одного чанка."""
    parts: list[str] = []

    if conversation_map and conversation_map.summary:
        parts.append(
            "О ЧЁМ ВЕСЬ РАЗГОВОР (общий контекст, извлекать отсюда НЕЛЬЗЯ):\n"
            + conversation_map.summary
        )
        if conversation_map.roles_mentioned:
            parts.append(
                "Роли, упомянутые на встрече: "
                + ", ".join(conversation_map.roles_mentioned)
            )
        if conversation_map.glossary:
            gloss = "\n".join(
                f"  {k} — {v}" for k, v in list(conversation_map.glossary.items())[:20]
            )
            parts.append("Термины заказчика:\n" + gloss)

    if chunk.overlap_text:
        parts.append(
            "ХВОСТ ПРЕДЫДУЩЕГО ФРАГМЕНТА (только для понимания контекста, "
            "извлекать отсюда НЕЛЬЗЯ):\n" + chunk.overlap_text
        )

    parts.append(
        f"ФРАГМЕНТ РАЗГОВОРА ДЛЯ АНАЛИЗА "
        f"(фрагмент {chunk.index + 1}, извлекай только отсюда):\n{chunk.text}"
    )
    parts.append(
        "Извлеки все элементы из фрагмента для анализа. "
        "Верни JSON вида {\"items\": [...]}."
    )
    return "\n\n".join(parts)


