TYPE_DEFINITIONS = """\
ТИПЫ ЭЛЕМЕНТОВ (используй строго эти значения поля "type"):

1. "functional_requirement" — функциональное требование.
   Что система должна уметь делать. Проверяемое утверждение вида
   «Система должна …» или «Пользователь должен иметь возможность …».
   НЕ роль, НЕ пошаговый сценарий, НЕ запрет.

2. "user_scenario" — пользовательский сценарий.
   Последовательность шагов, которой пользователь достигает цели.
   Отвечает на вопрос «как это происходит по шагам». Если в разговоре
   описан порядок действий — это сценарий, а не требование.

3. "user_role" — роль пользователя.
   Тип пользователя или действующее лицо системы: «бухгалтер», «руководитель
   отдела», «внешний аудитор», «администратор». В поле text — краткое описание
   роли и её задач в системе. Никаких действий-требований здесь.

4. "constraint" — ограничение.
   Жёсткая рамка, которую нельзя нарушить: технологии, сроки, бюджет,
   безопасность, законодательство, объёмы, обязательные интеграции.
   Маркеры: «нельзя», «только», «не более», «обязательно на», «запрещено».

5. "condition" — важное условие.
   Бизнес-правило или условие, при котором требование действует.
   Маркеры: «если …, то …», «при условии», «в случае когда», «кроме случаев».
   Отличие от ограничения: условие описывает ситуацию, ограничение — запрет
   или предел.

6. "open_question" — открытый вопрос.
   То, что на встрече не решили и что нужно уточнить.
   Маркеры: «надо уточнить», «пока не знаем», «вернёмся к этому», «спрошу
   у коллег», «это ещё обсуждается». В поле text сформулируй вопрос явно.

7. "agreement" — договорённость.
   То, о чём стороны явно условились. Маркеры: «договорились», «решили»,
   «остановимся на», «хорошо, делаем так», «фиксируем». Включай сюда же
   договорённости о сроках, следующих шагах и зонах ответственности.

Разграничение, если сомневаешься:
  — «Пользователь должен видеть отчёт» → functional_requirement
  — «Сначала он заходит, потом выбирает период, потом жмёт выгрузку» → user_scenario
  — «Отчёты смотрит только главбух» → user_role (главбух) + constraint (доступ)
  — «Только на нашем железе, облако не рассматриваем» → constraint
  — «Если сумма больше 100 тысяч — нужно второе согласование» → condition
  — «Надо будет уточнить у юристов» → open_question
  — «Договорились: первый релиз без мобильной версии» → agreement
"""

QUOTE_RULES = """\
ПРАВИЛА ЦИТИРОВАНИЯ (нарушение = элемент будет отброшен):
  * "quote" — ДОСЛОВНЫЙ фрагмент из текста разговора, скопированный посимвольно.
    Не пересказывай, не исправляй грамматику, не склеивай куски из разных мест.
  * Длина цитаты — от 5 до 40 слов: достаточно, чтобы понять контекст.
  * "segment_ids" — номера из маркеров [#N] тех строк, откуда взята цитата.
  * Если для элемента нет прямой цитаты — не выдумывай её, а не создавай элемент.

ЗАПРЕТ НА ДОДУМЫВАНИЕ:
  * Извлекай только то, что реально прозвучало. Не достраивай «типовые»
    требования, которых в разговоре не было.
  * Если поле неизвестно — ставь null или пустой список, а не догадку.
  * Одна мысль — один элемент. Не склеивай два требования в одно.
"""

