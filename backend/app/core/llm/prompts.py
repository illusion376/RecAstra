"""
Промпты конвейера.

Здесь сосредоточена вся «предметная» часть решения. Главное, что делают эти
промпты и чего не даёт наивное «скормить транскрипт целиком»:

  * жёсткие определения семи типов — без них модель валит требования,
    условия и договорённости в одну кучу;
  * обязательная дословная цитата-якорь у каждого элемента — это и трассировка
    до фрагмента разговора (пункт 5 кейса), и детектор галлюцинаций:
    цитату, которой нет в транскрипте, мы поймаем механически;
  * запрет додумывать — если в разговоре чего-то не было, поле остаётся пустым;
  * контекстный блок отделён от рабочего и помечен как «не извлекать»,
    иначе на каждом стыке чанков получаем дубли.
"""

