"""
Замер разделимости для дедупликации.

Отвечает на вопрос «каким порогом схожести склеивать дубли»: считает меру
на парах, которые склеивать надо, и на парах, которые склеивать нельзя.
Результат — обоснование решения в README: одним порогом эти классы
не разделяются, поэтому серую зону досматривает модель.

Запускать после правок в core/dedup.py:

    python probe_dedup.py
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))

from app.core.dedup import similarity  # noqa: E402
from app.schemas import Item, ItemType  # noqa: E402


def mk(title: str, text: str, t: ItemType = ItemType.FUNCTIONAL_REQUIREMENT) -> Item:
    return Item(analysis_id="probe", type=t, title=title, text=text)


# Одна и та же мысль, сказанная разными словами.
SAME = [
    (
        "Вход по корпоративной учётной записи",
        "Пользователь должен иметь возможность входить через корпоративную учётную запись.",
        "Авторизация через корпоративную учётку",
        "Вход в систему выполняется по корпоративной учётной записи пользователя.",
    ),
    (
        "Уведомления на почту",
        "Система должна присылать уведомление на электронную почту.",
        "Почтовые уведомления",
        "Система должна отправлять уведомления по электронной почте.",
    ),
    (
        "Хранение версий файла",
        "Нужно хранить все версии файла договора.",
        "Версионирование документа",
        "Система должна хранить все версии файла договора.",
    ),
]

# Разные требования с общей лексикой — самая опасная ловушка дедупликации.
DIFF = [
    (
        "Уведомление на почту",
        "Система должна присылать уведомление на электронную почту.",
        "Уведомление в телеграм",
        "Система должна присылать уведомление в телеграм.",
    ),
    (
        "Срок согласования юриста",
        "Юрист должен согласовать договор за три рабочих дня.",
        "Срок согласования бухгалтера",
        "Бухгалтер должен согласовать договор за два рабочих дня.",
    ),
    (
        "Выгрузка в эксель",
        "Руководитель должен выгружать отчёт в формате xlsx.",
        "Отчёт по срокам",
        "Руководитель должен видеть отчёт по срокам согласования договоров.",
    ),
    (
        "Комментарии к договору",
        "Участник должен иметь возможность оставить комментарий к договору.",
        "Запрет удаления договора",
        "Договор нельзя удалить, доступна только отмена.",
    ),
]


def main() -> None:
    print("ДОЛЖНЫ склеиться:")
    same = []
    for a1, a2, b1, b2 in SAME:
        s = similarity(mk(a1, a2), mk(b1, b2))
        same.append(s)
        print(f"  {s:.3f}  {a1}  <->  {b1}")

    print("\nНЕ должны склеиться:")
    diff = []
    for a1, a2, b1, b2 in DIFF:
        s = similarity(mk(a1, a2), mk(b1, b2))
        diff.append(s)
        print(f"  {s:.3f}  {a1}  <->  {b1}")

    lo, hi = max(diff), min(same)
    print(f"\nмин. среди «должны»:     {hi:.3f}")
    print(f"макс. среди «не должны»: {lo:.3f}")
    if hi > lo:
        print(f"РАЗДЕЛИМО одним порогом. Безопасное значение: {(lo + hi) / 2:.3f}")
    else:
        print(
            "НЕ РАЗДЕЛИМО одним порогом — классы перекрываются.\n"
            "Поэтому порог автосклейки строгий, а серую зону досматривает модель\n"
            "(AnalyzeOptions.llm_dedup)."
        )


if __name__ == "__main__":
    main()
